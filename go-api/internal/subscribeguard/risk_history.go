const riskHistorySchema = `
CREATE TABLE IF NOT EXISTS v2_subscribe_risk_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subject VARCHAR(80) NOT NULL, bucket BIGINT NOT NULL, score INTEGER NOT NULL,
 profile JSONB NOT NULL, assessed_at BIGINT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending', note TEXT NOT NULL DEFAULT '',
 reviewed_by BIGINT NOT NULL DEFAULT 0, reviewed_at BIGINT NOT NULL DEFAULT 0,
 revision BIGINT NOT NULL DEFAULT 0, UNIQUE(subject,bucket,score)
);
ALTER TABLE v2_subscribe_risk_history ADD COLUMN IF NOT EXISTS reason_key VARCHAR(64) NOT NULL DEFAULT '';
ALTER TABLE v2_subscribe_risk_history ADD COLUMN IF NOT EXISTS review_source BIGINT NOT NULL DEFAULT 0;
ALTER TABLE v2_subscribe_risk_history ADD COLUMN IF NOT EXISTS cooldown_until BIGINT NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS idx_subscribe_risk_history_time ON v2_subscribe_risk_history(assessed_at,id);
CREATE INDEX IF NOT EXISTS idx_subscribe_risk_history_status ON v2_subscribe_risk_history(status,id DESC);
CREATE INDEX IF NOT EXISTS idx_subscribe_risk_history_cooldown ON v2_subscribe_risk_history(subject,reason_key,reviewed_at DESC) WHERE status='false_positive';`

type RiskHistoryEntry struct {
	ID            int64       `json:"id"`
	Profile       RiskProfile `json:"profile"`
	AssessedAt    int64       `json:"assessed_at"`
	Status        string      `json:"status"`
	Note          string      `json:"note"`
	ReviewedBy    int64       `json:"reviewed_by"`
	ReviewedAt    int64       `json:"reviewed_at"`
	Revision      int64       `json:"revision"`
	ReviewSource  int64       `json:"review_source"`
	CooldownUntil int64       `json:"cooldown_until"`
}

type RiskHistoryFilter struct {
	Keyword  string
	Status   string
	Current  int
	PageSize int
}

type RiskHistoryResult struct {
	Data     []RiskHistoryEntry `json:"data"`
	Total    int64              `json:"total"`
	Current  int                `json:"current"`
	PageSize int                `json:"page_size"`
}

func (store *Store) captureRiskHistory(ctx context.Context, now int64) error {
	var lease int64
	err := store.db.QueryRowContext(ctx, `UPDATE v2_subscribe_monitor_control SET snapshot_next=$1::bigint+60 WHERE id=1 AND snapshot_next<=$1 RETURNING snapshot_next`, now).Scan(&lease)
	if errors.Is(err, sql.ErrNoRows) {
		return nil
	}
	if err != nil {
		return err
	}
	profiles, err := store.riskProfilesAt(ctx, "", now)
	if err != nil {
		return err
	}
	return store.saveRiskHistory(ctx, profiles, now)
}

func (store *Store) saveRiskHistory(ctx context.Context, profiles []RiskProfile, now int64) error {
	tx, err := store.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var lease int64
	if err := tx.QueryRowContext(ctx, `SELECT id FROM v2_subscribe_monitor_control WHERE id=1 FOR UPDATE`).Scan(&lease); err != nil {
		return err
	}
	decisionTime := max(now, time.Now().Unix())
	for _, profile := range profiles {
		if profile.Score < 60 {
			continue
		}
		raw, err := json.Marshal(profile)
		if err != nil {
			return err
		}
		if _, err = tx.ExecContext(ctx, `INSERT INTO v2_subscribe_risk_history(subject,bucket,score,profile,assessed_at,reason_key,status,review_source,cooldown_until)
SELECT $1::varchar,$2::bigint,$3::integer,$4::jsonb,$5::bigint,$6::varchar,CASE WHEN prior.id IS NULL THEN 'pending' ELSE 'suppressed' END,COALESCE(prior.id,0),COALESCE(prior.reviewed_at+86400,0)
FROM (SELECT 1) seed LEFT JOIN LATERAL (
SELECT id,reviewed_at FROM v2_subscribe_risk_history WHERE subject=$1::varchar AND reason_key=$6::varchar AND status='false_positive'
AND reviewed_at>$7::bigint-86400 AND reviewed_at<=$7::bigint ORDER BY reviewed_at DESC,id DESC LIMIT 1
) prior ON true ON CONFLICT(subject,bucket,score) DO NOTHING`, profile.Subject, now/3600, profile.Score, raw, now, riskReasonKey(profile), decisionTime); err != nil {
			return err
		}
	}
	if _, err = tx.ExecContext(ctx, `DELETE FROM v2_subscribe_risk_history WHERE id IN
(SELECT id FROM v2_subscribe_risk_history WHERE assessed_at<$1::bigint-2592000 ORDER BY assessed_at LIMIT 1000)`, now); err != nil {
		return err
	}
	if _, err = tx.ExecContext(ctx, `UPDATE v2_subscribe_monitor_control SET snapshot_at=$1 WHERE id=1`, now); err != nil {
		return err
	}
	return tx.Commit()
}

func (store *Store) RiskHistory(ctx context.Context, filter RiskHistoryFilter) (RiskHistoryResult, error) {
	result := RiskHistoryResult{Data: []RiskHistoryEntry{}, Current: filter.Current, PageSize: filter.PageSize}
	if !store.monitorReady.Load() {
		return result, ErrMonitorUnavailable
	}
	if filter.Current < 1 || filter.Current > 100000 || filter.PageSize < 1 || filter.PageSize > 100 || len(filter.Keyword) > 255 ||
		(filter.Status != "" && filter.Status != "pending" && filter.Status != "handled" && filter.Status != "false_positive" && filter.Status != "suppressed") {
		return result, errors.New("invalid history query")
	}
	condition := ` FROM v2_subscribe_risk_history WHERE ($1='' OR status=$1)
AND ($2='' OR profile->>'user_id'=$2 OR profile->>'token_hash'=$2 OR profile->>'ip'=$2 OR STRPOS(LOWER(profile->>'email'),LOWER($2))>0)`
	keyword := strings.TrimSpace(filter.Keyword)
	if err := store.db.QueryRowContext(ctx, `SELECT COUNT(*)`+condition, filter.Status, keyword).Scan(&result.Total); err != nil {
		return result, err
	}
	rows, err := store.db.QueryContext(ctx, `SELECT id,profile,assessed_at,status,note,reviewed_by,reviewed_at,revision,review_source,cooldown_until`+condition+` ORDER BY id DESC LIMIT $3 OFFSET $4`, filter.Status, keyword, filter.PageSize, (filter.Current-1)*filter.PageSize)
	if err != nil {
		return result, err
	}
	defer rows.Close()
	for rows.Next() {
		var entry RiskHistoryEntry
		var raw []byte
		if err := rows.Scan(&entry.ID, &raw, &entry.AssessedAt, &entry.Status, &entry.Note, &entry.ReviewedBy, &entry.ReviewedAt, &entry.Revision, &entry.ReviewSource, &entry.CooldownUntil); err != nil {
			return result, err
		}
		if err := json.Unmarshal(raw, &entry.Profile); err != nil {
			return result, err
		}
		result.Data = append(result.Data, entry)
	}
	return result, rows.Err()
}

func (store *Store) ReviewRisk(ctx context.Context, id, revision, adminID int64, status, note string) error {
	if !store.monitorReady.Load() {
		return ErrMonitorUnavailable
	}
	note = strings.TrimSpace(note)
	if id <= 0 || adminID <= 0 || revision < 0 || (status != "handled" && status != "false_positive") || note == "" || len([]rune(note)) > 500 {
		return errors.New("invalid risk review")
	}
	tx, err := store.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var controlID int64
	if err := tx.QueryRowContext(ctx, `SELECT id FROM v2_subscribe_monitor_control WHERE id=1 FOR UPDATE`).Scan(&controlID); err != nil {
		return err
	}
	var raw []byte
	err = tx.QueryRowContext(ctx, `SELECT profile FROM v2_subscribe_risk_history WHERE id=$1 AND revision=$2 AND status='pending' FOR UPDATE`, id, revision).Scan(&raw)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrConflict
	}
	if err != nil {
		return err
	}
	var profile RiskProfile
	if err := json.Unmarshal(raw, &profile); err != nil {
		return err
	}
	now := time.Now().Unix()
	key := riskReasonKey(profile)
	_, err = tx.ExecContext(ctx, `UPDATE v2_subscribe_risk_history SET status=$1::varchar,note=$2,reviewed_by=$3,reviewed_at=$4::bigint,revision=revision+1,reason_key=$7,
cooldown_until=CASE WHEN $1::varchar='false_positive' THEN $4::bigint+86400 ELSE 0 END WHERE id=$5 AND revision=$6 AND status='pending'`, status, note, adminID, now, id, revision, key)
	if err != nil {
		return err
	}
	if status == "false_positive" {
		_, err = tx.ExecContext(ctx, `UPDATE v2_subscribe_risk_history SET status='suppressed',review_source=$1,cooldown_until=$2::bigint+86400,revision=revision+1
WHERE subject=$3 AND reason_key=$4 AND status='pending' AND assessed_at >= $2::bigint-86400`, id, now, profile.Subject, key)
		if err != nil {
			return err
		}
	}
	return tx.Commit()
}

func riskReasonKey(profile RiskProfile) string {
	factors := append([]RiskFactor{}, profile.Factors...)
	sort.Slice(factors, func(left, right int) bool {
		if factors[left].Label != factors[right].Label {
			return factors[left].Label < factors[right].Label
		}
		return factors[left].Points < factors[right].Points
	})
	evidence := struct {
		Factors         []RiskFactor
		IP, UA, Country string
		ASN             int64
		Score           int
	}{factors, profile.IP, profile.UA, profile.Intelligence.CountryCode, profile.Intelligence.ASN, profile.Score}
	raw, _ := json.Marshal(evidence)
	digest := sha256.Sum256(raw)
	return hex.EncodeToString(digest[:])
}
