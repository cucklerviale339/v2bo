func EnsureClientEntrySchema(ctx context.Context, db *sql.DB) error {
	if db == nil {
		return fmt.Errorf("db is nil")
	}

	for _, stmt := range []string{
		`CREATE TABLE IF NOT EXISTS v2_client_entry_group (
id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
code varchar(64) NOT NULL,
name varchar(255) NOT NULL,
display_name varchar(255) NOT NULL,
strategy varchar(32) NOT NULL,
hide_member_nodes SMALLINT NOT NULL DEFAULT 0,
"show" SMALLINT NOT NULL DEFAULT 1,
remote_enabled SMALLINT NOT NULL DEFAULT 0,
remote_host varchar(255) NOT NULL DEFAULT '',
remote_ssh_port INTEGER NOT NULL DEFAULT 22,
remote_ssh_user varchar(255) NOT NULL DEFAULT '',
remote_ssh_password text NOT NULL DEFAULT '',
remote_group_ref varchar(255) NOT NULL DEFAULT '',
remote_exclude_names text NOT NULL DEFAULT '[]',
remote_refresh_sec INTEGER NOT NULL DEFAULT 300,
created_at INTEGER NOT NULL,
updated_at INTEGER NOT NULL,
PRIMARY KEY (id),
CONSTRAINT uniq_v2_client_entry_group_code UNIQUE (code)
)`,
		`CREATE TABLE IF NOT EXISTS v2_client_entry_group_member (
id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
entry_group_id INTEGER NOT NULL,
server_type varchar(16) NOT NULL,
server_id INTEGER NOT NULL,
sort INTEGER DEFAULT NULL,
created_at INTEGER NOT NULL,
updated_at INTEGER NOT NULL,
PRIMARY KEY (id),
CONSTRAINT uniq_v2_client_entry_group_member UNIQUE (entry_group_id, server_type, server_id)
)`,
		`CREATE TABLE IF NOT EXISTS v2_client_entry_group_ip (
id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
entry_group_id INTEGER NOT NULL,
ip varchar(128) NOT NULL,
sort INTEGER DEFAULT NULL,
created_at INTEGER NOT NULL,
updated_at INTEGER NOT NULL,
PRIMARY KEY (id),
CONSTRAINT uniq_v2_client_entry_group_ip UNIQUE (entry_group_id, ip)
)`,
	} {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("ensure client entry table: %w", err)
		}
	}

	for _, item := range []struct {
		table  string
		column string
		stmt   string
	}{
		{"v2_client_entry_group", "remote_enabled", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_enabled SMALLINT NOT NULL DEFAULT 0`},
		{"v2_client_entry_group", "remote_host", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_host varchar(255) NOT NULL DEFAULT ''`},
		{"v2_client_entry_group", "remote_ssh_port", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_ssh_port INTEGER NOT NULL DEFAULT 22`},
		{"v2_client_entry_group", "remote_ssh_user", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_ssh_user varchar(255) NOT NULL DEFAULT ''`},
		{"v2_client_entry_group", "remote_ssh_password", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_ssh_password text NOT NULL DEFAULT ''`},
		{"v2_client_entry_group", "remote_group_ref", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_group_ref varchar(255) NOT NULL DEFAULT ''`},
		{"v2_client_entry_group", "remote_exclude_names", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_exclude_names text NOT NULL DEFAULT '[]'`},
		{"v2_client_entry_group", "remote_refresh_sec", `ALTER TABLE v2_client_entry_group ADD COLUMN remote_refresh_sec INTEGER NOT NULL DEFAULT 300`},
	} {
		exists, err := columnExists(ctx, db, item.table, item.column)
		if err != nil {
			return fmt.Errorf("check client entry column %s.%s: %w", item.table, item.column, err)
		}
		if exists {
			continue
		}
		if _, err := db.ExecContext(ctx, item.stmt); err != nil {
			return fmt.Errorf("ensure client entry column %s.%s: %w", item.table, item.column, err)
		}
	}

	for _, stmt := range []string{
		`CREATE INDEX IF NOT EXISTS idx_v2_client_entry_group_member_group ON v2_client_entry_group_member(entry_group_id)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_client_entry_group_ip_group ON v2_client_entry_group_ip(entry_group_id)`,
	} {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("ensure client entry index: %w", err)
		}
	}

	return nil
}

func EnsureNodeAddressSchema(ctx context.Context, db *sql.DB) error {
	if db == nil {
		return fmt.Errorf("db is nil")
	}

	for _, stmt := range []string{
		`CREATE TABLE IF NOT EXISTS v2_node_address_group (
id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
name varchar(255) NOT NULL,
description text NOT NULL DEFAULT '',
enabled SMALLINT NOT NULL DEFAULT 1,
created_at INTEGER NOT NULL,
updated_at INTEGER NOT NULL,
PRIMARY KEY (id)
)`,
		`CREATE TABLE IF NOT EXISTS v2_node_address_rule (
id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
group_id INTEGER NOT NULL,
name varchar(255) NOT NULL DEFAULT '',
host varchar(255) NOT NULL,
match_user_ids text NOT NULL DEFAULT '[]',
match_user_id_ranges text NOT NULL DEFAULT '[]',
enabled SMALLINT NOT NULL DEFAULT 1,
sort INTEGER DEFAULT NULL,
created_at INTEGER NOT NULL,
updated_at INTEGER NOT NULL,
PRIMARY KEY (id)
)`,
		`CREATE TABLE IF NOT EXISTS v2_node_address_binding (
id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
address_group_id INTEGER NOT NULL,
server_type varchar(16) NOT NULL,
server_id INTEGER NOT NULL,
created_at INTEGER NOT NULL,
updated_at INTEGER NOT NULL,
PRIMARY KEY (id),
CONSTRAINT uniq_v2_node_address_binding UNIQUE (server_type, server_id)
)`,
	} {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("ensure node address table: %w", err)
		}
	}

	for _, tableName := range []string{"v2_node_address_group", "v2_node_address_rule"} {
		if err := ensureNodeAddressEnabledColumn(ctx, db, tableName); err != nil {
			return err
		}
	}
	if err := ensureNodeAddressRuleIDRangesColumn(ctx, db); err != nil {
		return err
	}

	for _, stmt := range []string{
		`CREATE INDEX IF NOT EXISTS idx_v2_node_address_rule_group ON v2_node_address_rule(group_id)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_address_binding_group ON v2_node_address_binding(address_group_id)`,
		`CREATE INDEX IF NOT EXISTS idx_v2_node_address_binding_server ON v2_node_address_binding(server_type, server_id)`,
	} {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("ensure node address index: %w", err)
		}
	}

	return nil
}

func ensureNodeAddressRuleIDRangesColumn(ctx context.Context, db *sql.DB) error {
	exists, err := columnExists(ctx, db, "v2_node_address_rule", "match_user_id_ranges")
	if err != nil {
		return fmt.Errorf("check node address user ID ranges column: %w", err)
	}
	if exists {
		return nil
	}
	if _, err := db.ExecContext(ctx, `ALTER TABLE v2_node_address_rule ADD COLUMN match_user_id_ranges text NOT NULL DEFAULT '[]'`); err != nil {
		return fmt.Errorf("add node address user ID ranges column: %w", err)
	}
	return nil
}

func ensureNodeAddressEnabledColumn(ctx context.Context, db *sql.DB, tableName string) error {
	switch tableName {
	case "v2_node_address_group", "v2_node_address_rule":
	default:
		return fmt.Errorf("unsupported node address table: %s", tableName)
	}

	enabledExists, err := columnExists(ctx, db, tableName, "enabled")
	if err != nil {
		return fmt.Errorf("check node address enabled column %s: %w", tableName, err)
	}
	showExists, err := columnExists(ctx, db, tableName, "show")
	if err != nil {
		return fmt.Errorf("check node address show column %s: %w", tableName, err)
	}

	if !enabledExists && showExists {
		if _, err := db.ExecContext(ctx, fmt.Sprintf(`ALTER TABLE %s RENAME COLUMN "show" TO enabled`, tableName)); err != nil {
			return fmt.Errorf("rename node address show column %s: %w", tableName, err)
		}
		enabledExists = true
		showExists = false
	}
	if !enabledExists {
		if _, err := db.ExecContext(ctx, fmt.Sprintf(`ALTER TABLE %s ADD COLUMN enabled SMALLINT NOT NULL DEFAULT 1`, tableName)); err != nil {
			return fmt.Errorf("add node address enabled column %s: %w", tableName, err)
		}
	}
	if showExists {
		if _, err := db.ExecContext(ctx, fmt.Sprintf(`ALTER TABLE %s DROP COLUMN "show"`, tableName)); err != nil {
			return fmt.Errorf("drop node address show column %s: %w", tableName, err)
		}
	}
	return nil
}

func columnExists(ctx context.Context, db *sql.DB, tableName, columnName string) (bool, error) {
	const query = `SELECT EXISTS (
SELECT 1 FROM information_schema.columns
WHERE table_schema = CURRENT_SCHEMA() AND table_name = $1 AND column_name = $2
)`
	var exists bool
	if err := db.QueryRowContext(ctx, query, tableName, columnName).Scan(&exists); err != nil {
		return false, err
	}
	return exists, nil
}
